#!/usr/bin/env bash
#
# Behaviour tests for `.github/scripts/checks/is-version-bump.sh`.
#
# The script decides whether a pull request is nothing but a podup version
# bump, which is the one case where the Podman lane may skip its VMs
# although Cargo.toml and friends changed. A wrong "yes" lets a code or
# dependency change through without the integration suite, so the cases
# below are mostly refusals, and each refusal asserts the diagnostic as
# well as the exit status: a script that exits 1 for the wrong reason
# (a typo, a missing tool) would otherwise pass every one of them.
#
# Each case builds a throwaway git repository with a realistic
# Cargo.toml, Cargo.lock and debian/changelog, commits it as `base`,
# applies one change, commits that as `head`, and runs the script on
# base..head. The `seed_*` variables bend the base to reach the
# cases that need a different starting point.
#
# Requires: bash, git, awk, the script under test.
set -uo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../../.." && pwd)"
script="$HERE/.github/scripts/checks/is-version-bump.sh"
[ -f "$script" ] || { echo "FAIL  $script does not exist"; exit 1; }

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

# Hermetic git: no user or system config, no signing, no hooks.
export GIT_CONFIG_NOSYSTEM=1 GIT_CONFIG_GLOBAL=/dev/null GIT_TERMINAL_PROMPT=0
export GIT_AUTHOR_NAME=t GIT_AUTHOR_EMAIL=t@example.invalid
export GIT_COMMITTER_NAME=t GIT_COMMITTER_EMAIL=t@example.invalid

pass=0
fail=0

check() { # <description> <expected> <actual>
	if [ "$2" = "$3" ]; then
		echo "ok    $1"
		pass=$((pass + 1))
	else
		echo "FAIL  $1"
		echo "        expected: $2"
		echo "        actual:   $3"
		fail=$((fail + 1))
	fi
}

# Starting point. BASE_VER and the seed_* switches bend it.
BASE_VER=5.13.0
seed() {
	mkdir -p src debian
	if [ -n "${seed_dep_first:-}" ]; then
		printf '[dependencies.foo]\nversion = "1.0.0"\n\n' >Cargo.toml
	else
		: >Cargo.toml
	fi
	cat >>Cargo.toml <<EOF
[package]
name = "podup"
version = "$BASE_VER"
edition = "2021"
rust-version = "1.88"

[dependencies]
serde = { version = "1.0.200", features = ["derive"] }
clap = "4"
EOF
	if [ -n "${seed_dep_after:-}" ]; then
		printf '\n[dependencies.foo]\nversion = "1.0.0"\n' >>Cargo.toml
	fi
	echo 'fn main() {}' >src/main.rs
	if [ -z "${seed_no_lock:-}" ]; then
		cat >Cargo.lock <<EOF
# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "clap"
version = "4.5.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "1111111111111111111111111111111111111111111111111111111111111111"

[[package]]
name = "podup"
version = "$BASE_VER"
dependencies = [
 "clap",
]
EOF
	fi
	if [ -n "${seed_empty_changelog:-}" ]; then
		: >debian/changelog
	elif [ -z "${seed_no_changelog:-}" ]; then
		cat >debian/changelog <<EOF
podup ($BASE_VER) unstable; urgency=medium

  * The previous release.
  * A second line of it.

 -- A B <a@example.invalid>  Mon, 01 Jan 2026 00:00:00 +0000

podup (5.12.0) unstable; urgency=medium

  * The one before.

 -- A B <a@example.invalid>  Mon, 01 Dec 2025 00:00:00 +0000
EOF
	fi
}

# Changes. Each runs inside the repository, after the base commit.
pkg_version() { # <file> <version>: the version line right after name = "podup"
	sed -i "/^name = \"podup\"\$/{n;s/.*/version = \"$2\"/}" "$1"
}
new_entry() {
	{
		printf 'podup (5.14.0) unstable; urgency=medium\n\n  * A change.\n\n'
		printf ' -- A B <a@example.invalid>  Mon, 01 Feb 2026 00:00:00 +0000\n\n'
		cat debian/changelog
	} >cl.new && mv cl.new debian/changelog
}
bump_toml() { pkg_version Cargo.toml 5.14.0; }
bump_lock() { pkg_version Cargo.lock 5.14.0; }
bump_all() { bump_toml; bump_lock; new_entry; }
bump_lock_and_toml() { bump_toml; bump_lock; }
adds_lock() {
	bump_toml; new_entry
	printf '[[package]]\nname = "podup"\nversion = "5.14.0"\n' >Cargo.lock
}
adds_changelog() {
	bump_toml; bump_lock
	printf 'podup (5.14.0) unstable; urgency=medium\n\n  * A change.\n' >debian/changelog
}
deletes_lock() { bump_toml; new_entry; rm Cargo.lock; }
deletes_changelog() { bump_toml; bump_lock; rm debian/changelog; }
bump_and_rs() { bump_all; echo '// touched' >>src/main.rs; }
bump_and_dep() { bump_all; sed -i 's/^clap = "4"$/clap = "5"/' Cargo.toml; }
bump_and_edition() { bump_all; sed -i 's/^edition = .*/edition = "2024"/' Cargo.toml; }
lock_other_version() { bump_all; sed -i 's/^version = "4.5.0"$/version = "4.6.0"/' Cargo.lock; }
lock_checksum() { bump_all; sed -i 's/^checksum = "1/checksum = "2/' Cargo.lock; }
lock_second_podup() {
	bump_all
	printf '\n[[package]]\nname = "podup"\nversion = "9.9.9"\n' >>Cargo.lock
}
lock_dangling_podup() { bump_all; printf '\n[[package]]\nname = "podup"\n' >>Cargo.lock; }
lock_podup_no_version() {
	bump_all
	printf '\n[[package]]\nname = "podup"\nsource = "elsewhere"\n' >>Cargo.lock
}
bump_and_late_dep() { bump_all; sed -i 's/^version = "1.0.0"$/version = "1.0.1"/' Cargo.toml; }
changelog_edit_old() { bump_all; sed -i 's/^  \* The one before\.$/  * The one before, reworded./' debian/changelog; }
changelog_drop_old() { bump_all; sed -i '/^  \* A second line of it\.$/d' debian/changelog; }
changelog_shrink() { bump_toml; sed -i '1,6d' debian/changelog; }
changelog_only() { new_entry; }
changelog_and_lock() { bump_lock; new_entry; }
changelog_other_name() {
	bump_toml; bump_lock
	{ printf 'other (5.14.0) unstable; urgency=medium\n\n'; cat debian/changelog; } >cl.new
	mv cl.new debian/changelog
}
changelog_partial_line() {
	bump_toml; bump_lock
	{ printf 'podup (5.14.0) unstable; urgency=medium'; cat debian/changelog; } >cl.new
	mv cl.new debian/changelog
}
toml_rc() { bump_all; sed -i 's/^version = "5.14.0"$/version = "5.14.0-rc1"/' Cargo.toml; }
toml_tail() { bump_all; sed -i 's/^version = "5.14.0"$/version = "5.14.0" # bump/' Cargo.toml; }
lock_rc() { bump_all; sed -i 's/^version = "5.14.0"$/version = "5.14.0-rc1"/' Cargo.lock; }
dep_version_only() { sed -i 's/^version = "1.0.0"$/version = "1.0.1"/' Cargo.toml; }
nothing() { :; }

# <description> <expected exit> <diagnostic substring or ""> <change>
run_case() {
	local d
	d="$(mktemp -d "$WORK/repo.XXXXXX")"
	(
		cd "$d" || exit 1
		git init -q . && git config commit.gpgsign false || exit 1
		seed
		git add -A && git commit -q -m base && git tag base || exit 1
		"$4"
		git add -A && git commit -q --allow-empty -m head && git tag head || exit 1
	) >"$d/setup.log" 2>&1 || { echo "FAIL  $1 (could not build the repository)"; cat "$d/setup.log"; fail=$((fail + 1)); return; }
	local rc=0
	(cd "$d" && bash "$script" "${RANGE_BASE:-base}" "${RANGE_HEAD:-head}" >"$d/out" 2>&1 </dev/null) || rc=$?
	check "$1" "$2" "$rc"
	if [ -n "$3" ]; then
		check "$1: says why" "1" "$(grep -cF -- "$3" "$d/out")"
	fi
}

run_case "a pure bump of Cargo.toml, Cargo.lock and the changelog passes" 0 "" bump_all
run_case "a bump of Cargo.toml and Cargo.lock without a changelog passes" 0 "" bump_lock_and_toml
run_case "a bump with a source file touched is refused" 1 "src/main.rs is not part of a version bump" bump_and_rs
run_case "a bump that also changes a dependency in Cargo.toml is refused" 1 "Cargo.toml changes more than the version" bump_and_dep
run_case "a bump that also changes the edition is refused" 1 "Cargo.toml changes more than the version" bump_and_edition
run_case "a bump that changes another package's version in Cargo.lock is refused" 1 "Cargo.lock changes more than the version" lock_other_version
run_case "a bump that changes a checksum in Cargo.lock is refused" 1 "Cargo.lock changes more than the version" lock_checksum
run_case "a second podup package in Cargo.lock is refused" 1 "Cargo.lock in head has no usable version line" lock_second_podup
run_case "a podup package without a version line in Cargo.lock is refused" 1 "Cargo.lock in head has no usable version line" lock_podup_no_version
run_case "a podup package cut off at the end of Cargo.lock is refused" 1 "Cargo.lock in head has no usable version line" lock_dangling_podup
seed_dep_after=1 run_case "a dependency version after [package] changing with the bump is refused" 1 "Cargo.toml changes more than the version" bump_and_late_dep
run_case "a changelog that edits an earlier line is refused" 1 "edits or removes an earlier line" changelog_edit_old
run_case "a changelog that drops an earlier line is refused" 1 "edits or removes an earlier line" changelog_drop_old
run_case "a changelog that shrinks is refused" 1 "did not grow" changelog_shrink
run_case "a changelog alone is refused" 1 "without a version change" changelog_only
run_case "a changelog with only Cargo.lock is refused" 1 "without a version change" changelog_and_lock
run_case "a changelog whose first entry is not podup is refused" 1 "does not start with a podup entry" changelog_other_name
run_case "a changelog that adds a partial line is refused" 1 "adds a partial line" changelog_partial_line
run_case "a Cargo.toml version with a suffix is refused" 1 "version in head is not plain X.Y.Z" toml_rc
run_case "a Cargo.toml version with trailing text is refused" 1 "version in head is not plain X.Y.Z" toml_tail
run_case "a Cargo.lock version with a suffix is refused" 1 "version in head is not plain X.Y.Z" lock_rc
BASE_VER=5.13.0-rc1 run_case "a suffix on the base version is refused" 1 "version in base is not plain X.Y.Z" bump_all
run_case "an empty range is refused" 1 "empty range" nothing
RANGE_HEAD=deadbeefdeadbeefdeadbeefdeadbeefdeadbeef \
	run_case "a SHA that does not exist is refused" 1 "cannot resolve" bump_all
seed_no_lock=1 run_case "Cargo.lock absent in the base is refused" 1 "Cargo.lock is missing in" adds_lock
run_case "Cargo.lock absent in the head is refused" 1 "Cargo.lock is missing in head" deletes_lock
run_case "a changelog absent in the head is refused" 1 "debian/changelog is missing in head" deletes_changelog
seed_no_changelog=1 run_case "a changelog absent in the base is refused" 1 "debian/changelog is missing in" adds_changelog
seed_empty_changelog=1 run_case "an empty changelog in the base is refused" 1 "is empty in" bump_all
seed_dep_first=1 run_case "a dependency version before [package] is refused" 1 "no usable version line" dep_version_only
seed_dep_first=1 run_case "a bump with a dependency version before [package] is refused" 1 "no usable version line" bump_all

# The workflow does not run the checked-out script: it pipes the copy that
# lives in the base commit, so a pull request cannot edit its own judge. These
# cases run that exact invocation. <description> <expected> <base has script:
# 1|0> <change>
run_via_base() {
	local d rc=0
	d="$(mktemp -d "$WORK/repo.XXXXXX")"
	(
		cd "$d" || exit 1
		git init -q . && git config commit.gpgsign false || exit 1
		seed
		mkdir -p .github/scripts/checks
		[ "$3" = 1 ] && cp "$script" .github/scripts/checks/is-version-bump.sh
		git add -A && git commit -q -m base && git tag base || exit 1
		"$4"
		git add -A && git commit -q --allow-empty -m head && git tag head || exit 1
	) >"$d/setup.log" 2>&1 || { echo "FAIL  $1 (could not build the repository)"; cat "$d/setup.log"; fail=$((fail + 1)); return; }
	(
		cd "$d" || exit 1
		set -o pipefail
		git show base:.github/scripts/checks/is-version-bump.sh | bash -s -- base head
	) >"$d/out" 2>&1 || rc=$?
	# Any non-zero status (a failed `git show` is 128) means: not a bump.
	[ "$rc" -eq 0 ] || rc=1
	check "$1" "$2" "$rc"
}
# A pull request that rewrites the script to say yes to everything, and
# touches source too.
rigged_script() {
	printf '#!/usr/bin/env bash\nexit 0\n' >.github/scripts/checks/is-version-bump.sh
	echo '// touched' >>src/main.rs
	bump_all
}
run_via_base "a pure bump judged by the base copy of the script passes" 0 1 bump_all
run_via_base "a script absent in the base is not a bump" 1 0 bump_all
run_via_base "a pull request that rigs the script is still judged by the base copy" 1 1 rigged_script
# shellcheck disable=SC2016  # the pattern is literal text from the workflow
check "the workflow reads the script from the base commit" "1" \
	"$(grep -cF 'git show "$BASE_SHA:.github/scripts/checks/is-version-bump.sh"' "$HERE/.github/workflows/podman-lane.yml")"
check "the workflow does not run the checked-out copy" "0" \
	"$(grep -cE '^[[:space:]]*if bash \.github/scripts/checks/is-version-bump\.sh' "$HERE/.github/workflows/podman-lane.yml")"

# Called with the wrong number of arguments, it refuses before touching git.
out="$(bash "$script" 2>&1 </dev/null)"
check "no arguments is refused" "1" "$?"
check "no arguments: says why" "1" "$(printf '%s\n' "$out" | grep -cF 'usage: is-version-bump.sh BASE HEAD')"

echo
echo "passed: $pass  failed: $fail"
printf 'DONE %s %d %d\n' "${BASH_SOURCE[0]##*/}" "$pass" "$fail"
[ "$fail" -eq 0 ]
